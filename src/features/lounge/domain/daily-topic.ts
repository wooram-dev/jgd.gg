export function getDailyTopics(now: Date) {
  const period = getRankingPeriod("today", now);
  const day = Math.floor(period.startsAt!.getTime() / 86_400_000);
  const pair = TOPICS[((day % TOPICS.length) + TOPICS.length) % TOPICS.length];
  return [
    { id: "daily", label: "가벼운 수다", question: pair[0] },
    { id: "gaming", label: "게임 이야기", question: pair[1] },
  ];
}
